//! M3 semantic colour model.
//!
//! Every colour in the system is a *role*, not a value: `ColorRole` names the
//! slot in Material's semantic palette, and something upstream
//! runs material_color_utilities) turns one source colour into concrete RGBs
//! for all of them. A component asks for `ColorRole.primary_container`, never
//! for "the light blue", so re-theming a whole shell is a palette swap and
//! nothing in the control layer has to change.
//!
//! `ColorSpec` is how a call site picks between "use the role" and "use this
//! exact colour" — the `fixed` flag short-circuits the role lookup, and
//! `alpha` is a 0–255 override layered on top of either source. Keeping the
//! alpha in bytes rather than a float, matching the ARGB packing
//! the rest of the paint code does.

/// A linear RGB triple, unpremultiplied and unclamped
/// (`m3::Rgb` layout). Callers that feed cairo do the clamping.
pub const Rgb = struct {
    r: f32,
    g: f32,
    b: f32,
};

/// All 53 colour roles generated by material_color_utilities from a single
/// source colour. Ordered by palette family, so the enum's numeric order
/// matches the palette table's row order.
///
/// Porting note: the upstream comment promises 53 roles (material_color_utilities
/// generates that many) but the enum itself only declares the 47 below — the
/// surface tonal and fixed-palette variants are partly absent. This port
/// matches what the declaration provides, not what the comment claims, so indices
/// stay aligned with the palette table.
pub const ColorRole = enum {
    // — Primary palette —
    primary, // Main brand accent. Filled button bg, active states.
    on_primary, // Content (text, icons) ON primary-coloured areas.
    primary_container, // Container variant. Tonal buttons, selected chips.
    on_primary_container, // Content ON primary-container.
    primary_fixed, // Light-mode fixed primary (no dark-mode shift).
    primary_fixed_dim, // Dimmer version of primary-fixed.
    on_primary_fixed, // Content on primary-fixed.
    on_primary_fixed_variant, // Variant content on primary-fixed.

    // — Secondary palette —
    secondary, // Secondary brand accent.
    on_secondary, // Content ON secondary.
    secondary_container, // Container variant.
    on_secondary_container, // Content ON secondary-container.
    secondary_fixed,
    secondary_fixed_dim,
    on_secondary_fixed,
    on_secondary_fixed_variant,

    // — Tertiary palette —
    tertiary, // Tertiary brand accent. Progress, input focus.
    on_tertiary,
    tertiary_container,
    on_tertiary_container,
    tertiary_fixed,
    tertiary_fixed_dim,
    on_tertiary_fixed,
    on_tertiary_fixed_variant,

    // — Error palette —
    @"error", // Destructive colour.
    on_error, // Content ON error.
    error_container, // Container variant.
    on_error_container,

    // — Surface palette (light → dark gradient) —
    surface, // Default page / app background.
    on_surface, // Primary text content.
    surface_variant, // Slightly shifted surface for cards, menus.
    on_surface_variant, // Secondary text, captions.

    // Surface tonal variants (M3 Expressive 2025):
    surface_dim, // Darkest surface family member.
    surface_bright, // Lightest surface family member.
    surface_container_lowest, // Below-surface container (drawer bg).
    surface_container_low, // Low container (search bar bg).
    surface_container, // Default container (nav bar, bottom sheet bg).
    surface_container_high, // High container (dialog bg).
    surface_container_highest, // Highest container (menu, popup bg).

    // — Inverse palette —
    inverse_surface, // Inverted surface (snackbar, tooltip bg).
    inverse_on_surface, // Content on inverse-surface.
    inverse_primary, // Primary for UI on surface (snackbar button).

    // — Other —
    outline, // Strong borders, dividers (moderate emphasis).
    outline_variant, // Low-emphasis borders (disabled, subtle dividers).
    shadow, // Shadow colour for elevation.
    scrim, // Scrim / overlay dim background.
    surface_tint, // Overlay tint for elevation colour shift.

    /// Total roles declared. A palette is exactly this long.
    pub const count: usize = reflection.enumFields(ColorRole).len;
};

test "m3-tokens-color: 47 declared roles, in palette order" {
    const t = std.testing;
    // 47 roles — see the note on ColorRole.
    try t.expectEqual(@as(usize, 47), ColorRole.count);
    // The role order pins the palette row order — a reordering here would
    // silently retheme everything downstream of a table indexed by this enum.
    try t.expectEqual(ColorRole.primary, @as(ColorRole, @enumFromInt(0)));
    try t.expectEqual(ColorRole.surface_tint, @as(ColorRole, @enumFromInt(46)));
    // The four palette families stay contiguous, which is what makes a
    // "walk the primary family" loop safe.
    try t.expectEqual(@as(u8, 8), @intFromEnum(ColorRole.secondary) - @intFromEnum(ColorRole.primary));
    try t.expectEqual(@as(u8, 4), @intFromEnum(ColorRole.@"error") - @intFromEnum(ColorRole.tertiary_fixed));
}

/// A colour specification can reference a semantic role OR provide a fixed RGB
/// + optional alpha override.
pub const ColorSpec = struct {
    role: ColorRole,
    /// 0–255 opacity override (255 = use the role's full opacity).
    alpha: u8 = 255,
    /// true = use fixed_r/g/b instead of `role`.
    fixed: bool = false,
    fixed_r: f32 = 0.0,
    fixed_g: f32 = 0.0,
    fixed_b: f32 = 0.0,
};

const std = @import("std");
const reflection = @import("../../compat/reflection.zig");

test "m3-tokens-color: spec defaults favour the role" {
    const t = std.testing;
    const s = ColorSpec{ .role = .primary };
    try t.expect(!s.fixed);
    try t.expectEqual(@as(u8, 255), s.alpha);
    try t.expectEqual(@as(f32, 0.0), s.fixed_r);
}
